export const CRYPTO_ASSETS_MAP: Record<string, CryptoAssetDefinition> = Object.fromEntries(
  CRYPTO_ASSETS.map((asset) => [asset.ticker.toUpperCase(), asset])
);

export const ALL_CRYPTO_TICKERS: string[] = CRYPTO_ASSETS.map((a) => a.ticker);

export function findCryptoAsset(tickerOrCode: string): CryptoAssetDefinition | undefined {
  if (!tickerOrCode) return undefined;
  const upper = tickerOrCode.toUpperCase().trim();
  if (CRYPTO_ASSETS_MAP[upper]) return CRYPTO_ASSETS_MAP[upper];

  // Try matching by code (e.g. "BTC" or "PEPE")
  const matchCode = CRYPTO_ASSETS.find((a) => a.code.toUpperCase() === upper);
  if (matchCode) return matchCode;

  // Try matching clean prefix without -USD
  const cleanTicker = upper.replace(/-USD$/, "").replace(/-USDT$/, "").replace(/-TRY$/, "");
  const matchClean = CRYPTO_ASSETS.find(
    (a) => a.code.toUpperCase() === cleanTicker || a.ticker.replace(/-USD$/, "") === cleanTicker
  );
  if (matchClean) return matchClean;

  return undefined;
}
