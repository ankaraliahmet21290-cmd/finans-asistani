export const US_STOCK_MAP: Record<string, UsStockAssetDefinition> = Object.fromEntries(
  US_STOCK_ASSETS.map((stock) => [stock.ticker.toUpperCase(), stock])
);

export const ALL_US_STOCK_TICKERS: string[] = US_STOCK_ASSETS.map((s) => s.ticker);

export const FEATURED_US_STOCK_TICKERS: string[] = US_STOCK_ASSETS.filter((s) => s.featured).map(
  (s) => s.ticker
);

export const US_STOCK_ALIASES: Record<string, string> = {
  MMC: "MRSH",
  SQ: "XYZ",
};

export function findUsStockAsset(tickerOrCode: string): UsStockAssetDefinition | undefined {
  if (!tickerOrCode) return undefined;
  let upper = tickerOrCode.toUpperCase().trim();
  if (US_STOCK_ALIASES[upper]) {
    upper = US_STOCK_ALIASES[upper];
  }
  if (US_STOCK_MAP[upper]) return US_STOCK_MAP[upper];

  // Match by code (e.g. BRK-B or BRK.B)
  const normalized = upper.replace(/\./g, "-");
  if (US_STOCK_MAP[normalized]) return US_STOCK_MAP[normalized];

  const match = US_STOCK_ASSETS.find(
    (s) => s.code.toUpperCase() === upper || s.code.toUpperCase() === normalized
  );
  if (match) return match;

  return undefined;
}
